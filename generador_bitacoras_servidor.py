"""
## Bloque 3. Generador lineal congruencial (LCG)

Se implementa un generador lineal congruencial para producir valores pseudoaleatorios reproducibles mediante la expresión:

**Xₙ₊₁ = (aXₙ + c) mod m**

La semilla y los parámetros permanecen fijos, permitiendo obtener los mismos resultados en cada ejecución. Estos valores se utilizarán posteriormente para generar las sesiones del servidor.
"""

# ==================================================
# BLOQUE 3: GENERADOR LINEAL CONGRUENCIAL (LCG)
# ==================================================

class GeneradorLCG:
    def __init__(self, semilla=2026):
        self.semilla = semilla
        self.estado = semilla

        # Parámetros del generador
        self.a = 1664525
        self.c = 1013904223
        self.m = 2**32

    def siguiente(self):
        self.estado = (self.a * self.estado + self.c) % self.m
        return self.estado

    def entero(self, minimo, maximo):
        """Genera un entero dentro del intervalo indicado."""
        return minimo + self.siguiente() % (maximo - minimo + 1)


# Inicializar el generador
